"""Register-level model of how software operates OpenDMA.

The model follows the register descriptions (chapter 3) and the programming sequences (chapter 4) of the published
register interface, the AXI DMA product guide PG021 v7.1. It is written from the product guide only, independently of
the RTL and without vendor driver code. A Scenario collects steps (reset, start of a channel, transfers) and writes
the files the sequence player of the testbenches executes (hdl/odma_pkg/docs/architecture.md, section 3.3):

- sequence.txt                 register accesses, interrupt waits and stream packets
- memory.txt                   initial memory image of the MM2S read port (source buffers)
- expected_memory.txt          memory contents expected after the scenario on the S2MM write port (destination
                               buffers)
- desc_memory.txt              initial memory image of the descriptor port (Scatter/Gather Mode)
- expected_desc_memory.txt     descriptors expected after the scenario, with their status words

Usage from a VUnit pre_config: scenario.write(output_path); from the command line:
python tb/model/odma_model.py <scenario> <directory>
"""

import random
import sys
from dataclasses import dataclass
from pathlib import Path


class Regs:
    """Register offsets and fields (PG021 Tables 4 to 24)."""

    # Offsets relative to the channel base (MM2S 0x00, S2MM 0x30)
    DMACR = 0x00
    DMASR = 0x04
    CURDESC = 0x08       # Scatter/Gather Mode (Table 4)
    CURDESC_MSB = 0x0C
    TAILDESC = 0x10
    TAILDESC_MSB = 0x14
    ADDR = 0x18          # MM2S_SA, S2MM_DA
    ADDR_MSB = 0x1C      # MM2S_SA_MSB, S2MM_DA_MSB
    LENGTH = 0x28        # MM2S_LENGTH (0x28), S2MM_LENGTH (0x58)
    BASE = {"MM2S": 0x00, "S2MM": 0x30}

    # DMACR fields
    RS = 1 << 0
    RESET = 1 << 2
    CYCLIC_BD = 1 << 4
    IOC_IRQ_EN = 1 << 12
    DLY_IRQ_EN = 1 << 13
    ERR_IRQ_EN = 1 << 14
    IRQ_THRESHOLD_RESET = 0x01 << 16

    # DMASR fields
    HALTED = 1 << 0
    IDLE = 1 << 1
    DMA_INT_ERR = 1 << 4
    DMA_SLV_ERR = 1 << 5
    DMA_DEC_ERR = 1 << 6
    SG_INT_ERR = 1 << 8
    SG_SLV_ERR = 1 << 9
    SG_DEC_ERR = 1 << 10
    IOC_IRQ = 1 << 12
    DLY_IRQ = 1 << 13
    ERR_IRQ = 1 << 14
    # State, error and interrupt flags checked after a transfer
    STATE = (HALTED | IDLE | DMA_INT_ERR | DMA_SLV_ERR | DMA_DEC_ERR | SG_INT_ERR | SG_SLV_ERR | SG_DEC_ERR
             | IOC_IRQ | DLY_IRQ | ERR_IRQ)


def count_bytes(n, seed):
    """n bytes with the values (seed + i) mod 256."""
    return bytes((seed + i) % 256 for i in range(n))


@dataclass
class DrTransfer:
    """One transfer in Direct Register Mode."""

    channel: str          # "MM2S" or "S2MM"
    addr: int             # buffer address
    data: bytes           # MM2S: bytes read from the buffer; S2MM: the received packet
    irq: bool = True      # completion by interrupt (True) or by polling DMASR.Idle (False)
    buffer_len: int = 0   # S2MM: value of S2MM_LENGTH (0: the packet length)


class Scenario:
    """Steps of a test and the generator of its files."""

    def __init__(self, name, addr_width=32, timeout=100000, channels=("MM2S", "S2MM"), guard=0):
        self.name = name
        self.addr_width = addr_width
        self.timeout = timeout
        self.channels = channels  # included channels
        self.guard = guard        # bytes before and after each S2MM buffer that must stay unwritten (0x00)
        self.lines = [f"# OpenDMA sequence {name}, generated by tb/model/odma_model.py"]
        self.memory = []      # (address, bytes)
        self.expected = []    # (address, bytes)
        self.desc_memory = []     # (address, bytes): descriptors (Scatter/Gather Mode)
        self.desc_expected = []   # (address, bytes): descriptors after the scenario

    # -----------------------------------------------------------------------------------------------------------------
    # Primitives of the sequence file
    # -----------------------------------------------------------------------------------------------------------------
    def comment(self, text):
        self.lines.append(f"L {text}")

    def write_reg(self, offset, value):
        self.lines.append(f"W 0x{offset:02X} 0x{value:08X}")

    def read_reg(self, offset, expected, mask=0xFFFFFFFF):
        self.lines.append(f"R 0x{offset:02X} 0x{expected:08X} 0x{mask:08X}")

    def poll_reg(self, offset, expected, mask):
        self.lines.append(f"P 0x{offset:02X} 0x{expected:08X} 0x{mask:08X} {self.timeout}")

    def wait_irq(self, channel, level):
        self.lines.append(f"I {channel} {level} {self.timeout}")

    def packet(self, command, data):
        self.lines.append(f"{command} " + " ".join(f"{b:02X}" for b in data))

    # -----------------------------------------------------------------------------------------------------------------
    # Steps
    # -----------------------------------------------------------------------------------------------------------------
    def reset(self):
        """Soft reset through DMACR.Reset (resets the whole core, PG021 Table 6), written to the first included
        channel; the included channels halted."""
        base = Regs.BASE[self.channels[0]]
        self.comment("soft reset")
        self.write_reg(base + Regs.DMACR, Regs.IRQ_THRESHOLD_RESET | Regs.RESET)
        self.poll_reg(base + Regs.DMACR, 0, Regs.RESET)
        for ch in self.channels:
            self.read_reg(Regs.BASE[ch] + Regs.DMASR, Regs.HALTED, Regs.HALTED | Regs.IDLE)

    def check_cleared(self):
        """After a reset: the included channels halted without error and interrupt flags (PG021 Tables 7 and 17)."""
        for ch in self.channels:
            self.read_reg(Regs.BASE[ch] + Regs.DMASR, Regs.HALTED, Regs.STATE)

    def start(self, channel, irq=True):
        """PG021 chapter 4, DR mode steps 1 and 2: run/stop bit, halted bit deasserts, interrupt enables."""
        base = Regs.BASE[channel]
        self.comment(f"start {channel}")
        self.write_reg(base + Regs.DMACR, Regs.IRQ_THRESHOLD_RESET | Regs.RS)
        self.poll_reg(base + Regs.DMASR, 0, Regs.HALTED)
        if irq:
            self.write_reg(base + Regs.DMACR, Regs.IRQ_THRESHOLD_RESET | Regs.RS | Regs.IOC_IRQ_EN | Regs.ERR_IRQ_EN)

    def halt(self, channel):
        """PG021 Table 6: run/stop bit 0; DMASR.Halted follows once the channel has stopped."""
        base = Regs.BASE[channel]
        self.comment(f"halt {channel}")
        self.write_reg(base + Regs.DMACR, Regs.IRQ_THRESHOLD_RESET)
        self.poll_reg(base + Regs.DMASR, Regs.HALTED, Regs.HALTED)

    def _program(self, t, written=None, stream=True):
        """PG021 chapter 4, DR mode: address (and its MSB register above 32 address bits), the length as the last
        write, the stream packet unless stream is False. written: the bytes of an S2MM packet that reach the buffer
        (default: all)."""
        base = Regs.BASE[t.channel]
        self.comment(f"{t.channel} transfer of {len(t.data)} bytes at 0x{t.addr:X}")
        self.write_reg(base + Regs.ADDR, t.addr & 0xFFFFFFFF)
        if self.addr_width > 32:
            self.write_reg(base + Regs.ADDR_MSB, t.addr >> 32)
        if t.channel == "MM2S":
            if stream:
                self.memory.append((t.addr, t.data))
            self.write_reg(base + Regs.LENGTH, len(t.data))
            if stream:
                self.packet("E", t.data)
        else:
            self.write_reg(base + Regs.LENGTH, t.buffer_len or len(t.data))
            if stream:
                self.packet("S", t.data)
            written = t.data if written is None else written
            if written:
                self.expected.append((t.addr, written))
                if self.guard:
                    self.expected.append((t.addr - self.guard, bytes(self.guard)))
                    self.expected.append((t.addr + len(written), bytes(self.guard)))

    def _complete(self, t):
        """Completion by interrupt or by polling DMASR.Idle, IOC_Irq cleared by writing one; S2MM: the received
        length."""
        base = Regs.BASE[t.channel]
        if t.irq:
            self.wait_irq(t.channel, 1)
        else:
            self.poll_reg(base + Regs.DMASR, Regs.IDLE, Regs.IDLE)
        self.read_reg(base + Regs.DMASR, Regs.IDLE | Regs.IOC_IRQ, Regs.STATE)
        self.write_reg(base + Regs.DMASR, Regs.IOC_IRQ)
        if t.irq:
            self.wait_irq(t.channel, 0)
        if t.channel == "S2MM":
            self.read_reg(base + Regs.LENGTH, len(t.data))

    def transfer(self, t):
        """One transfer and its completion."""
        self._program(t)
        self._complete(t)
        self.lines.append("A")

    def concurrent(self, transfers):
        """Transfers of both channels at the same time (the channels operate independently): every transfer is
        programmed before the first completion is awaited."""
        self.comment("concurrent transfers")
        for t in transfers:
            self._program(t)
        for t in transfers:
            self._complete(t)
        self.lines.append("A")

    def failed_transfer(self, t, errors, written=b"", stream=True):
        """A transfer that ends with an error (PG021 Tables 7 and 17): the error flags and Err_Irq are set, RS falls,
        and DMASR.Halted follows when the channel has shut down; software clears Err_Irq by writing one, the error
        flags stay until a reset. written: the bytes of an S2MM packet that reach the buffer; stream: False when the
        transfer moves no stream data."""
        base = Regs.BASE[t.channel]
        self._program(t, written, stream)
        if t.irq:
            self.wait_irq(t.channel, 1)
        self.poll_reg(base + Regs.DMASR, Regs.HALTED, Regs.HALTED)
        self.read_reg(base + Regs.DMASR, Regs.HALTED | errors | Regs.ERR_IRQ, Regs.STATE)
        self.write_reg(base + Regs.DMASR, Regs.ERR_IRQ)
        if t.irq:
            self.wait_irq(t.channel, 0)
        self.lines.append("A")

    # -----------------------------------------------------------------------------------------------------------------
    # Files
    # -----------------------------------------------------------------------------------------------------------------
    @staticmethod
    def _image(ranges):
        return "".join(f"0x{addr:016X} " + " ".join(f"{b:02X}" for b in data) + "\n" for addr, data in ranges)

    def write(self, directory):
        directory = Path(directory)
        directory.mkdir(parents=True, exist_ok=True)
        (directory / "sequence.txt").write_text("\n".join(self.lines) + "\n", encoding="utf-8", newline="\n")
        (directory / "memory.txt").write_text(self._image(self.memory), encoding="utf-8", newline="\n")
        (directory / "expected_memory.txt").write_text(self._image(self.expected), encoding="utf-8", newline="\n")
        (directory / "desc_memory.txt").write_text(self._image(self.desc_memory), encoding="utf-8", newline="\n")
        (directory / "expected_desc_memory.txt").write_text(self._image(self.desc_expected), encoding="utf-8",
                                                            newline="\n")

    # -----------------------------------------------------------------------------------------------------------------
    # Scatter/Gather Mode (PG021 chapter 4, "Scatter Gather Mode"; descriptors of Tables 25 to 40)
    # -----------------------------------------------------------------------------------------------------------------
    def _pointer(self, channel, reg, value):
        """A descriptor pointer register: the low word, above 32 address bits the upper word last (SGI-01)."""
        base = Regs.BASE[channel]
        self.write_reg(base + reg, value & 0xFFFFFFFF)
        if self.addr_width > 32:
            self.write_reg(base + reg + 4, value >> 32)

    def sg_start(self, channel, curdesc, threshold=1, cyclic=False, delay=0):
        """Steps 1 to 3: CURDESC, the run/stop bit with the interrupt enables, the threshold and the delay (with
        Dly_IrqEn when not 0), Halted deasserts."""
        base = Regs.BASE[channel]
        self.comment(f"start {channel} at descriptor 0x{curdesc:X}")
        self._pointer(channel, Regs.CURDESC, curdesc)
        dmacr = (delay << 24 | threshold << 16 | Regs.RS | Regs.IOC_IRQ_EN | Regs.ERR_IRQ_EN
                 | (Regs.DLY_IRQ_EN if delay else 0) | (Regs.CYCLIC_BD if cyclic else 0))
        self.write_reg(base + Regs.DMACR, dmacr)
        self.poll_reg(base + Regs.DMASR, 0, Regs.HALTED)

    def sg_tail(self, channel, tail):
        """Step 4: the tail pointer starts or continues the engine."""
        self.comment(f"{channel} tail at 0x{tail:X}")
        self._pointer(channel, Regs.TAILDESC, tail)

    def sg_descriptors(self, chain, written):
        """The descriptors of a chain in the initial image; the expected image with the status of the descriptors in
        written (indices); other descriptors unchanged."""
        self.desc_memory += chain.image()
        self.desc_expected += chain.expected(written)

    def sg_buffers(self, chain, indices, guard=None):
        """Buffers of the descriptors in indices: MM2S source data into the image and the packets expected on the
        stream; S2MM the packets sent and the expected memory."""
        guard = self.guard if guard is None else guard
        for i in indices:
            b = chain.buffers[i]
            if chain.channel == "MM2S":
                self.memory.append((b.addr, b.data))
                self.packet("E", b.data)
            else:
                self.packet("S", b.data)
                self.expected.append((b.addr, b.data))
                if guard:
                    self.expected.append((b.addr - guard, bytes(guard)))
                    self.expected.append((b.addr + len(b.data), bytes(guard)))

    def sg_complete(self, channel, tail):
        """The chain up to the tail is completed: Idle, IOC_Irq set and cleared, the interrupt output low, CURDESC
        at the tail (Tables 7, 8 and 17)."""
        base = Regs.BASE[channel]
        self.poll_reg(base + Regs.DMASR, Regs.IDLE, Regs.IDLE)
        self.read_reg(base + Regs.DMASR, Regs.IDLE | Regs.IOC_IRQ, Regs.STATE)
        self.write_reg(base + Regs.DMASR, Regs.IOC_IRQ)
        self.wait_irq(channel, 0)
        self.read_reg(base + Regs.CURDESC, tail & 0xFFFFFFFF)
        if self.addr_width > 32:
            self.read_reg(base + Regs.CURDESC_MSB, tail >> 32)

    def sg_failed(self, channel, errors, curdesc, ioc=False):
        """An error of the engine or of a transfer: Err_Irq, Halted after the shut down, the flags (IOC_Irq when a
        packet completed before), Err_Irq cleared, CURDESC at the descriptor of the error."""
        base = Regs.BASE[channel]
        self.wait_irq(channel, 1)
        self.poll_reg(base + Regs.DMASR, Regs.HALTED, Regs.HALTED)
        self.read_reg(base + Regs.DMASR, Regs.HALTED | errors | Regs.ERR_IRQ | (Regs.IOC_IRQ if ioc else 0),
                      Regs.STATE)
        self.write_reg(base + Regs.DMASR, Regs.ERR_IRQ)
        self.read_reg(base + Regs.CURDESC, curdesc & 0xFFFFFFFF)


DESC_BYTES = 32      # words 0x00 to 0x1C (no user application fields before phase c)


@dataclass
class SgBuffer:
    """One descriptor of a chain and the data of its buffer."""

    addr: int               # buffer address
    length: int             # buffer length of the descriptor
    data: bytes = b""       # MM2S: the bytes of the buffer; S2MM: the packet received into the buffer
    sof: bool = True        # MM2S TXSOF; S2MM: RXSOF expected
    eof: bool = True        # MM2S TXEOF; S2MM: RXEOF expected
    cmplt: bool = False     # completed bit in the initial image (a stale descriptor)


def _words(nxt, channel, b):
    control = b.length
    if channel == "MM2S":
        control |= (1 << 27 if b.sof else 0) | (1 << 26 if b.eof else 0)
    return [nxt & 0xFFFFFFFF, nxt >> 32, b.addr & 0xFFFFFFFF, b.addr >> 32, 0, 0, control, 1 << 31 if b.cmplt else 0]


def status_word(channel, b, errors=0):
    """Status of a descriptor after its transfer (Tables 31 and 38): transferred bytes, RXSOF and RXEOF (S2MM), the
    error flags, Cmplt only without an error (interpretation SGI-02)."""
    n = b.length if channel == "MM2S" else len(b.data)
    s = n | errors | (0 if errors else 1 << 31)
    if channel == "S2MM":
        s |= (1 << 27 if b.sof and n else 0) | (1 << 26 if b.eof else 0)
    return s


def _le(words):
    return b"".join(w.to_bytes(4, "little") for w in words)


class SgChain:
    """A ring of descriptors at 64-byte aligned addresses, 0x1C0 apart (crossing 4 KB boundaries)."""

    def __init__(self, channel, base, buffers, stride=0x1C0):
        self.channel = channel
        self.buffers = list(buffers)
        self.addrs = [base + i * stride for i in range(len(self.buffers))]

    def image(self):
        n = len(self.addrs)
        return [(a, _le(_words(self.addrs[(i + 1) % n], self.channel, b)))
                for i, (a, b) in enumerate(zip(self.addrs, self.buffers))]

    def expected(self, written, errors=None):
        """written: indices whose STATUS is written; errors: index -> error flags of its status."""
        errors = errors or {}
        out = []
        n = len(self.addrs)
        for i, (a, b) in enumerate(zip(self.addrs, self.buffers)):
            words = _words(self.addrs[(i + 1) % n], self.channel, b)
            if i in written:
                words[7] = status_word(self.channel, b, errors.get(i, 0))
            out.append((a, _le(words)))
        return out


# Descriptor regions of the memory model of the descriptor port (instance MemSg_c of the core bench)
DESC_BASE = {"MM2S": 0x0020_0000, "S2MM": 0x0030_0000}
ERR_DESC_READ_BASE = 0x0006_0000      # the core bench answers reads with SLVERR here
ERR_DESC_WRITE_BASE = 0x0007_0000     # and writes with SLVERR here


def _desc_base(channel, addr_width, high=False):
    base = DESC_BASE[channel]
    return base + (1 << (addr_width - 1)) if high and addr_width > 32 else base


def dr_reference():
    """Reference scenario of the model test (hdl/odma_pkg, TC-PKG-11): reset, one MM2S and one S2MM transfer with
    interrupt above 4 GB at unaligned addresses, one MM2S transfer by polling."""
    s = Scenario("dr_reference", addr_width=64)
    s.reset()
    s.start("MM2S")
    s.start("S2MM")
    s.transfer(DrTransfer("MM2S", 0x1_0000_0103, count_bytes(37, 0x10)))
    s.transfer(DrTransfer("S2MM", 0x1_0000_2005, count_bytes(29, 0x80), buffer_len=64))
    s.transfer(DrTransfer("MM2S", 0x3000, count_bytes(8, 0xC0), irq=False))
    return s


# Largest packet of the sequence player (hdl/odma_pkg/docs/architecture.md, section 3.3)
SEQ_MAX_BYTES = 16384

# Regions of the memory model that the core tests set to respond with SLVERR (hdl/odma_core/docs/verification_plan.md)
ERR_READ_BASE = 0x0004_0000
ERR_WRITE_BASE = 0x0005_0000
ERR_SIZE = 0x1000


def random_bytes(n, rng):
    """n bytes without a period, so that a byte at a wrong address or lane differs from the expected one."""
    return bytes(rng.randrange(256) for _ in range(n))


class Buffers:
    """Buffers that do not overlap, at unaligned addresses, in a low region and, above 32 address bits, in a region
    that sets the most significant address bit."""

    def __init__(self, addr_width, rng):
        self.rng = rng
        self.cursor = [0x0010_0000]
        if addr_width > 32:
            self.cursor.append((1 << (addr_width - 1)) + 0x0010_0000)

    def take(self, n, cross=False):
        """Address of a buffer of n bytes; cross: the buffer crosses a 4 KB boundary (n >= 2)."""
        region = self.rng.randrange(len(self.cursor))
        start = self.cursor[region] + self.rng.randrange(64)
        if cross and n >= 2:
            boundary = (start // 4096 + 2) * 4096
            start = boundary - self.rng.randrange(1, min(n - 1, 4095) + 1)
        self.cursor[region] = start + n + 256
        return start


def _length_limit(length_width):
    return min(2 ** length_width - 1, SEQ_MAX_BYTES)


def dr_random(addr_width=32, length_width=14, channels=("MM2S", "S2MM"), seed=1, count=12, name="dr_random"):
    """Transfers of random channels, lengths (among them 1 byte and the longest length) and unaligned buffer
    addresses, some across 4 KB boundaries, completed by interrupt or by polling; S2MM buffers longer than or as long
    as the packet; then a halt and a restart of each channel with one more transfer."""
    rng = random.Random(seed)
    limit = _length_limit(length_width)
    buffers = Buffers(addr_width, rng)
    s = Scenario(name, addr_width=addr_width, channels=channels, guard=16)
    s.reset()
    s.check_cleared()
    for ch in channels:
        s.start(ch)
    lengths = [1, limit] + [min(limit, rng.choice((rng.randint(1, 64), rng.randint(65, 1024),
                                                   rng.randint(1025, 6000)))) for _ in range(count - 2)]
    rng.shuffle(lengths)

    def one(n, irq):
        ch = rng.choice(channels)
        addr = buffers.take(n, cross=rng.random() < 0.4)
        if ch == "MM2S":
            return DrTransfer("MM2S", addr, random_bytes(n, rng), irq=irq)
        buffer_len = rng.choice((n, min(n + rng.randint(1, 200), 2 ** length_width - 1)))
        buffers.take(buffer_len - n)   # keep the rest of the buffer free
        return DrTransfer("S2MM", addr, random_bytes(n, rng), irq=irq, buffer_len=buffer_len)

    for n in lengths:
        s.transfer(one(n, rng.random() < 0.6))
    for ch in channels:
        s.halt(ch)
        s.start(ch)
        n = rng.randint(1, min(limit, 300))
        s.transfer(DrTransfer(ch, buffers.take(n), random_bytes(n, rng), irq=True))
    return s


def dr_concurrent(addr_width=32, length_width=14, seed=2):
    """Long MM2S and S2MM transfers at the same time, three by interrupt and one by polling."""
    rng = random.Random(seed)
    n = min(_length_limit(length_width), 8000)
    buffers = Buffers(addr_width, rng)
    s = Scenario("dr_concurrent", addr_width=addr_width, guard=16)
    s.reset()
    for ch in ("MM2S", "S2MM"):
        s.start(ch)
    for irq in (True, True, True, False):
        s.concurrent([DrTransfer("MM2S", buffers.take(n), random_bytes(n, rng), irq=irq),
                      DrTransfer("S2MM", buffers.take(n), random_bytes(n, rng), irq=irq)])
    return s


def dr_errors(addr_width=32, length_width=14, seed=3):
    """Errors and their recovery (PG021 Tables 7 and 17): an MM2S read error, an S2MM write error, an S2MM packet
    longer than its buffer and buffers of both channels beyond the top of the address space (OpenDMA interpretation
    I5: decode error without an access and without stream data), each followed by a transfer of the other channel
    without a reset and by a soft reset; the memory model answers SLVERR in ERR_READ_BASE (reads) and ERR_WRITE_BASE
    (writes)."""
    rng = random.Random(seed)
    buffers = Buffers(32, rng)
    s = Scenario("dr_errors", addr_width=addr_width, guard=16)

    def restart():
        s.reset()
        s.check_cleared()
        for ch in ("MM2S", "S2MM"):
            s.start(ch)

    def good(ch, n):
        n = min(n, _length_limit(length_width))
        s.transfer(DrTransfer(ch, buffers.take(n), random_bytes(n, rng)))

    restart()
    s.comment("MM2S read error: the packet is sent completely, DMASlvErr")
    s.failed_transfer(DrTransfer("MM2S", ERR_READ_BASE + 0x13, random_bytes(64, rng)), Regs.DMA_SLV_ERR)
    good("S2MM", 100)
    restart()
    s.comment("S2MM write error: DMASlvErr with DMAIntErr, the rest of the packet discarded")
    s.failed_transfer(DrTransfer("S2MM", ERR_WRITE_BASE + 0x21, random_bytes(100, rng), buffer_len=128),
                      Regs.DMA_SLV_ERR | Regs.DMA_INT_ERR)
    good("MM2S", 100)
    restart()
    s.comment("S2MM packet longer than the buffer: DMAIntErr, no byte beyond the buffer")
    data = random_bytes(200, rng)
    addr = buffers.take(200)
    s.failed_transfer(DrTransfer("S2MM", addr, data, buffer_len=120), Regs.DMA_INT_ERR, written=data[:120])
    good("MM2S", 50)
    restart()
    top = 2 ** addr_width - 0x20
    s.comment("MM2S buffer beyond the top of the address space: DMADecErr")
    s.failed_transfer(DrTransfer("MM2S", top, random_bytes(64, rng)), Regs.DMA_DEC_ERR, stream=False)
    good("S2MM", 70)
    restart()
    s.comment("S2MM buffer beyond the top of the address space: DMADecErr with DMAIntErr")
    s.failed_transfer(DrTransfer("S2MM", top, random_bytes(64, rng)), Regs.DMA_DEC_ERR | Regs.DMA_INT_ERR,
                      stream=False)
    good("MM2S", 70)
    restart()
    good("MM2S", 333)
    good("S2MM", 333)
    return s


def dr_single(channel, addr_width=32, length_width=14, seed=4, name="single"):
    """One transfer of 256 bytes (or the longest length) without a reset; the channel is started if it is halted."""
    rng = random.Random(seed)
    n = min(256, _length_limit(length_width))
    s = Scenario(name, addr_width=addr_width, channels=(channel,), guard=16)
    s.start(channel)
    s.transfer(DrTransfer(channel, Buffers(32, rng).take(n), random_bytes(n, rng)))
    return s


def _sg_chain(channel, n, addr_width, length_width, rng, buffers, high=False, base=None):
    """A chain of n single-buffer packets: MM2S buffers with random data (TXSOF and TXEOF in every descriptor),
    S2MM buffers that each receive one packet of up to their length."""
    limit = min(_length_limit(length_width), 2000)
    descs = []
    for _ in range(n):
        length = rng.randint(1, limit)
        if channel == "MM2S":
            descs.append(SgBuffer(buffers.take(length, cross=rng.random() < 0.3), length, random_bytes(length, rng)))
        else:
            size = rng.randint(1, length)
            descs.append(SgBuffer(buffers.take(length, cross=rng.random() < 0.3), length, random_bytes(size, rng)))
    return SgChain(channel, base if base is not None else _desc_base(channel, addr_width, high), descs)


def sg_reference(addr_width=32, length_width=14, channels=("MM2S", "S2MM"), seed=11, reset=True):
    """The programming sequence of Scatter/Gather Mode for each channel (PG021 chapter 4): a chain of four
    descriptors, each one packet, the interrupt after every packet; descriptors above 32 address bits when the
    address width allows. reset: False leaves out the soft reset at the start."""
    rng = random.Random(seed)
    buffers = Buffers(addr_width, rng)
    s = Scenario("sg_reference", addr_width=addr_width, channels=channels, guard=16)
    if reset:
        s.reset()
        s.check_cleared()
    for ch in channels:
        chain = _sg_chain(ch, 4, addr_width, length_width, rng, buffers, high=True)
        s.sg_descriptors(chain, range(4))
        s.sg_start(ch, chain.addrs[0])
        s.sg_tail(ch, chain.addrs[3])
        s.sg_buffers(chain, range(4))
        s.lines.append("A")
        s.sg_complete(ch, chain.addrs[3])
    return s


def sg_tail_moves(addr_width=32, length_width=14, channels=("MM2S", "S2MM"), seed=12, count=12):
    """Software moves the tail pointer while the channels run (DESCMGMT.TAIL): both channels together, the tail
    moved by one to four descriptors, sometimes while the engine still works and sometimes after it is idle."""
    rng = random.Random(seed)
    buffers = Buffers(addr_width, rng)
    s = Scenario("sg_tail_moves", addr_width=addr_width, channels=channels, guard=16)
    s.reset()
    chains = {ch: _sg_chain(ch, count, addr_width, length_width, rng, buffers) for ch in channels}
    for ch in channels:
        s.sg_descriptors(chains[ch], range(count))
        s.sg_start(ch, chains[ch].addrs[0], threshold=2)
    done = {ch: 0 for ch in channels}
    while any(done[ch] < count for ch in channels):
        for ch in channels:
            if done[ch] == count:
                continue
            step = min(rng.randint(1, 4), count - done[ch])
            s.sg_buffers(chains[ch], range(done[ch], done[ch] + step))
            done[ch] += step
            s.sg_tail(ch, chains[ch].addrs[done[ch] - 1])
        if rng.random() < 0.5:
            s.lines.append("A")
            for ch in channels:
                s.poll_reg(Regs.BASE[ch] + Regs.DMASR, Regs.IDLE, Regs.IDLE)
    s.lines.append("A")
    for ch in channels:
        base = Regs.BASE[ch]
        s.poll_reg(base + Regs.DMASR, Regs.IDLE, Regs.IDLE)
        s.write_reg(base + Regs.DMASR, Regs.IOC_IRQ | Regs.DLY_IRQ)
        s.read_reg(base + Regs.CURDESC, chains[ch].addrs[count - 1] & 0xFFFFFFFF)
    return s


def sg_cyclic(addr_width=32, length_width=14, channels=("MM2S", "S2MM"), seed=13, laps=2):
    """Cyclic mode (DMACR.CyclicBD, SEQ.CYCLIC): a ring of three descriptors per channel processed for two laps; the
    S2MM channel is halted after the last packet, the MM2S channel, which is already sending the third lap, by a soft
    reset."""
    rng = random.Random(seed)
    buffers = Buffers(addr_width, rng)
    s = Scenario("sg_cyclic", addr_width=addr_width, channels=channels, guard=16)
    s.reset()
    chains = {}
    for ch in channels:
        chains[ch] = _sg_chain(ch, 3, addr_width, length_width, rng, buffers)
        s.sg_descriptors(chains[ch], range(3))
        s.sg_start(ch, chains[ch].addrs[0], cyclic=True)
        s.sg_tail(ch, chains[ch].addrs[1])
    for lap in range(laps):
        for ch in channels:
            if ch == "MM2S":
                for b in chains[ch].buffers:
                    if lap == 0:
                        s.memory.append((b.addr, b.data))
                    s.packet("E", b.data)
            else:
                # Other bytes of the same lengths in the earlier laps: the buffers hold the last lap
                for b in chains[ch].buffers:
                    if lap == laps - 1:
                        s.packet("S", b.data)
                        s.expected.append((b.addr, b.data))
                    else:
                        s.packet("S", random_bytes(len(b.data), rng))
    s.lines.append("A")
    s.lines.append("D 2000")
    if "S2MM" in channels:
        s.halt("S2MM")
        s.read_reg(Regs.BASE["S2MM"] + Regs.CURDESC, chains["S2MM"].addrs[0] & 0xFFFFFFFF)
    s.reset()
    return s


def sg_errors(addr_width=32, length_width=14, channels=("MM2S", "S2MM"), seed=14):
    """Errors of Scatter/Gather Mode and their recovery by a soft reset: a descriptor fetch with SLVERR (SGSlvErr),
    a stale descriptor (SGIntErr), a buffer length of 0 (DMAIntErr in DMASR and in the status, Cmplt 0) and a status
    write with SLVERR (SGSlvErr); the memory model of the descriptor port answers SLVERR in ERR_DESC_READ_BASE (reads)
    and ERR_DESC_WRITE_BASE (writes). MM2S: the failing fetch and the stale descriptor are the second descriptor, and
    the first one, already issued, completes with its packet. S2MM: they are the first descriptor; a later one would
    halt the channel while the packet of the first one arrives, which then ends early (interpretation I8)."""
    rng = random.Random(seed)
    buffers = Buffers(32, rng)
    s = Scenario("sg_errors", addr_width=addr_width, channels=channels, guard=16)
    offset = 0

    def chain(ch, n, base=None):
        nonlocal offset
        c = _sg_chain(ch, n, addr_width, length_width, rng, buffers,
                      base=base if base is not None else DESC_BASE[ch] + offset)
        offset += 0x4000
        return c

    for ch in channels:
        s.reset()
        s.check_cleared()
        if ch == "MM2S":
            s.comment("MM2S: fetch of the second descriptor with SLVERR")
            c = chain(ch, 2)
            c.addrs[1] = ERR_DESC_READ_BASE
            s.sg_descriptors(c, [0])
            s.desc_memory = [d for d in s.desc_memory if d[0] != c.addrs[1]]
            s.desc_expected = [d for d in s.desc_expected if d[0] != c.addrs[1]]
            s.sg_start(ch, c.addrs[0])
            s.sg_tail(ch, c.addrs[1])
            s.sg_buffers(c, [0])
            s.lines.append("A")
            s.sg_failed(ch, Regs.SG_SLV_ERR, c.addrs[1], ioc=True)
        else:
            s.comment("S2MM: fetch of the first descriptor with SLVERR")
            err = ERR_DESC_READ_BASE + 0x40
            s.sg_start(ch, err)
            s.sg_tail(ch, err)
            s.sg_failed(ch, Regs.SG_SLV_ERR, err)

        s.reset()
        if ch == "MM2S":
            s.comment("MM2S: stale second descriptor")
            c = chain(ch, 3)
            c.buffers[1].cmplt = True
            s.sg_descriptors(c, [0])
            s.sg_start(ch, c.addrs[0])
            s.sg_tail(ch, c.addrs[2])
            s.sg_buffers(c, [0])
            s.lines.append("A")
            s.sg_failed(ch, Regs.SG_INT_ERR, c.addrs[1], ioc=True)
        else:
            s.comment("S2MM: stale first descriptor")
            c = chain(ch, 2)
            c.buffers[0].cmplt = True
            s.sg_descriptors(c, [])
            s.sg_start(ch, c.addrs[0])
            s.sg_tail(ch, c.addrs[1])
            s.sg_failed(ch, Regs.SG_INT_ERR, c.addrs[0])

        s.reset()
        s.comment(f"{ch}: buffer length 0")
        c = chain(ch, 2)
        c.buffers[0] = SgBuffer(c.buffers[0].addr, 0, b"", sof=ch == "MM2S", eof=ch == "MM2S")
        s.desc_memory += c.image()
        s.desc_expected += c.expected([0], {0: 1 << 28})
        s.sg_start(ch, c.addrs[0])
        s.sg_tail(ch, c.addrs[1])
        s.sg_failed(ch, Regs.DMA_INT_ERR, c.addrs[0])

        s.reset()
        s.comment(f"{ch}: status write with SLVERR")
        c = chain(ch, 2, base=ERR_DESC_WRITE_BASE + (0x400 if ch == "S2MM" else 0))
        s.desc_memory += c.image()
        s.desc_expected += c.expected([])
        s.sg_start(ch, c.addrs[0])
        s.sg_tail(ch, c.addrs[0])
        s.sg_buffers(c, [0])
        s.lines.append("A")
        s.sg_failed(ch, Regs.SG_SLV_ERR, c.addrs[0])
    s.reset()
    s.check_cleared()
    return s


def sg_delay(addr_width=32, length_width=14, channels=("MM2S", "S2MM"), seed=15, delay=4):
    """Interrupt delay with the threshold 2 (PG021 Tables 6 and 7; interpretations R9 and R10 of odma_registers): a
    single packet sets Dly_Irq when the delay timer expires; the start of the next packet stops the timer, so that a
    packet that lasts longer than the delay sets IOC_Irq at its completion and no Dly_Irq. The testbench holds every
    packet after its first stream beat for longer than the delay (1500 clock cycles, the delay 4 x 125 cycles). The
    next packet starts only after the completion of the one before: S2MM after the poll of the threshold counter,
    MM2S after the tail pointer write that follows the poll."""
    rng = random.Random(seed)
    buffers = Buffers(addr_width, rng)
    s = Scenario("sg_delay", addr_width=addr_width, channels=channels, guard=16)
    length = min(_length_limit(length_width), 200)
    for ch in channels:
        base = Regs.BASE[ch]
        s.reset()
        c = SgChain(ch, _desc_base(ch, addr_width),
                    [SgBuffer(buffers.take(length), length, random_bytes(length, rng)) for _ in range(3)])
        s.sg_descriptors(c, range(3))
        s.sg_start(ch, c.addrs[0], threshold=2, delay=delay)
        s.comment(f"{ch}: one packet, Dly_Irq when the timer expires")
        s.sg_tail(ch, c.addrs[0])
        s.sg_buffers(c, [0])
        s.lines.append("A")
        s.wait_irq(ch, 1)
        s.read_reg(base + Regs.DMASR, Regs.IDLE | Regs.DLY_IRQ, Regs.STATE)
        s.write_reg(base + Regs.DMASR, Regs.DLY_IRQ)
        s.wait_irq(ch, 0)
        s.comment(f"{ch}: the next packet starts while the timer runs and stops it")
        s.sg_tail(ch, c.addrs[1])
        s.sg_buffers(c, [1])
        s.lines.append("A")
        # Threshold counter 1: the packet has completed and the timer runs
        s.poll_reg(base + Regs.DMASR, 1 << 16, 0xFF << 16)
        s.sg_tail(ch, c.addrs[2])
        s.sg_buffers(c, [2])
        s.lines.append("A")
        s.wait_irq(ch, 1)
        s.read_reg(base + Regs.DMASR, Regs.IDLE | Regs.IOC_IRQ, Regs.STATE)
        # The threshold stopped the timer: no Dly_Irq later
        s.lines.append(f"D {2 * delay * 125}")
        s.read_reg(base + Regs.DMASR, Regs.IDLE | Regs.IOC_IRQ, Regs.STATE)
        s.write_reg(base + Regs.DMASR, Regs.IOC_IRQ)
        s.wait_irq(ch, 0)
    return s


def sg_delay_overlap(addr_width=32, length_width=14, channels=("MM2S", "S2MM"), stream_bytes=None, seed=16,
                     delay=4):
    """Interpretation R10 of odma_registers: a packet that starts before the completion of the one before does not
    stop the delay timer, which then runs during that packet. Two packets back to back with the threshold 2; the
    testbench holds every packet after its first stream beat for 400 clock cycles (shorter than the delay of 4 x 125
    cycles), so the first completes during the pause of the second; the second continues for at least 250 beats
    after the pause, longer than the rest of the delay. Dly_Irq is set and IOC_Irq is not; the threshold counter reads
    1 (reloaded by the timeout, decremented by the second packet). stream_bytes: bytes per stream beat per channel.
    The buffers and descriptors lie above those of sg_delay, which runs before in the same test."""
    rng = random.Random(seed)
    buffers = Buffers(addr_width, rng)
    buffers.cursor = [c + 0x0008_0000 for c in buffers.cursor]
    s = Scenario("sg_delay_overlap", addr_width=addr_width, channels=channels, guard=16)
    limit = _length_limit(length_width)
    for ch in channels:
        base = Regs.BASE[ch]
        beat = (stream_bytes or {}).get(ch, 4)
        lengths = (min(limit, 200), min(limit // beat, 300) * beat)
        s.reset()
        c = SgChain(ch, _desc_base(ch, addr_width) + 0x1000,
                    [SgBuffer(buffers.take(n), n, random_bytes(n, rng)) for n in lengths])
        s.sg_descriptors(c, range(2))
        s.sg_start(ch, c.addrs[0], threshold=2, delay=delay)
        s.comment(f"{ch}: the second packet starts before the completion of the first")
        s.sg_tail(ch, c.addrs[1])
        s.sg_buffers(c, [0, 1])
        s.lines.append("A")
        s.poll_reg(base + Regs.DMASR, Regs.IDLE, Regs.IDLE)
        s.read_reg(base + Regs.DMASR, Regs.IDLE | Regs.DLY_IRQ, Regs.STATE)
        s.read_reg(base + Regs.DMASR, 1 << 16, 0xFF << 16)
    s.reset()
    return s


def sg_reset_load(addr_width=32, length_width=14, channels=("MM2S", "S2MM"), seed=17):
    """Setup of the soft reset test of Scatter/Gather Mode (odma_core TC-CO-17): chains of four descriptors per
    channel started with the tail at the last one, without stream packets: the MM2S stream peer takes nothing, and
    the stream peer of the core bench sends the S2MM packet (at most the longest length, so the S2MM buffers have
    the longest length). Nothing is checked in memory: the soft reset interrupts the chains. The buffers lie above
    those of sg_reference, and the descriptors above its chains."""
    rng = random.Random(seed)
    buffers = Buffers(addr_width, rng)
    buffers.cursor = [c + 0x0040_0000 for c in buffers.cursor]
    s = Scenario("sg_reset_load", addr_width=addr_width, channels=channels)
    limit = _length_limit(length_width)
    s.reset()
    for ch in channels:
        n = min(limit, 4000) if ch == "MM2S" else limit
        c = SgChain(ch, _desc_base(ch, addr_width) + 0x8000,
                    [SgBuffer(buffers.take(n), n, random_bytes(n, rng)) for _ in range(4)])
        s.desc_memory += c.image()
        if ch == "MM2S":
            s.memory += [(b.addr, b.data) for b in c.buffers]
        s.sg_start(ch, c.addrs[0])
        s.sg_tail(ch, c.addrs[3])
    return s


