"""Register-level model of how software operates OpenDMA.

The model follows the register descriptions (chapter 3) and the programming sequences (chapter 4) of the published
register interface, the AXI DMA product guide PG021 v7.1. It is written from the product guide only, independently of
the RTL and without vendor driver code. A Scenario collects steps (reset, start of a channel, transfers) and writes
the files the sequence player of the testbenches executes (hdl/odma_pkg/docs/architecture.md, section 3.3):

- sequence.txt          register accesses, interrupt waits and stream packets
- memory.txt            initial memory image (source buffers)
- expected_memory.txt   memory contents expected after the scenario (destination buffers)

Usage from a VUnit pre_config: scenario.write(output_path); from the command line:
python tb/model/odma_model.py <scenario> <directory>
"""

import sys
from dataclasses import dataclass
from pathlib import Path


class Regs:
    """Register offsets and fields (PG021 Tables 4 to 24)."""

    # Offsets relative to the channel base (MM2S 0x00, S2MM 0x30)
    DMACR = 0x00
    DMASR = 0x04
    ADDR = 0x18          # MM2S_SA, S2MM_DA
    ADDR_MSB = 0x1C      # MM2S_SA_MSB, S2MM_DA_MSB
    LENGTH = 0x28        # MM2S_LENGTH (0x28), S2MM_LENGTH (0x58)
    BASE = {"MM2S": 0x00, "S2MM": 0x30}

    # DMACR fields
    RS = 1 << 0
    RESET = 1 << 2
    IOC_IRQ_EN = 1 << 12
    ERR_IRQ_EN = 1 << 14
    IRQ_THRESHOLD_RESET = 0x01 << 16

    # DMASR fields
    HALTED = 1 << 0
    IDLE = 1 << 1
    DMA_INT_ERR = 1 << 4
    DMA_SLV_ERR = 1 << 5
    DMA_DEC_ERR = 1 << 6
    SG_INT_ERR = 1 << 8
    SG_SLV_ERR = 1 << 9
    SG_DEC_ERR = 1 << 10
    IOC_IRQ = 1 << 12
    DLY_IRQ = 1 << 13
    ERR_IRQ = 1 << 14
    # State, error and interrupt flags checked after a transfer
    STATE = (HALTED | IDLE | DMA_INT_ERR | DMA_SLV_ERR | DMA_DEC_ERR | SG_INT_ERR | SG_SLV_ERR | SG_DEC_ERR
             | IOC_IRQ | DLY_IRQ | ERR_IRQ)


def count_bytes(n, seed):
    """n bytes with the values (seed + i) mod 256."""
    return bytes((seed + i) % 256 for i in range(n))


@dataclass
class DrTransfer:
    """One transfer in Direct Register Mode."""

    channel: str          # "MM2S" or "S2MM"
    addr: int             # buffer address
    data: bytes           # MM2S: bytes read from the buffer; S2MM: the received packet
    irq: bool = True      # completion by interrupt (True) or by polling DMASR.Idle (False)
    buffer_len: int = 0   # S2MM: value of S2MM_LENGTH (0: the packet length)


class Scenario:
    """Steps of a test and the generator of its files."""

    def __init__(self, name, addr_width=32, timeout=100000):
        self.name = name
        self.addr_width = addr_width
        self.timeout = timeout
        self.lines = [f"# OpenDMA sequence {name}, generated by tb/model/odma_model.py"]
        self.memory = []      # (address, bytes)
        self.expected = []    # (address, bytes)

    # -----------------------------------------------------------------------------------------------------------------
    # Primitives of the sequence file
    # -----------------------------------------------------------------------------------------------------------------
    def comment(self, text):
        self.lines.append(f"L {text}")

    def write_reg(self, offset, value):
        self.lines.append(f"W 0x{offset:02X} 0x{value:08X}")

    def read_reg(self, offset, expected, mask=0xFFFFFFFF):
        self.lines.append(f"R 0x{offset:02X} 0x{expected:08X} 0x{mask:08X}")

    def poll_reg(self, offset, expected, mask):
        self.lines.append(f"P 0x{offset:02X} 0x{expected:08X} 0x{mask:08X} {self.timeout}")

    def wait_irq(self, channel, level):
        self.lines.append(f"I {channel} {level} {self.timeout}")

    def packet(self, command, data):
        self.lines.append(f"{command} " + " ".join(f"{b:02X}" for b in data))

    # -----------------------------------------------------------------------------------------------------------------
    # Steps
    # -----------------------------------------------------------------------------------------------------------------
    def reset(self):
        """Soft reset through MM2S_DMACR.Reset (resets the whole core, PG021 Table 6); both channels halted."""
        self.comment("soft reset")
        self.write_reg(Regs.BASE["MM2S"] + Regs.DMACR, Regs.IRQ_THRESHOLD_RESET | Regs.RESET)
        self.poll_reg(Regs.BASE["MM2S"] + Regs.DMACR, 0, Regs.RESET)
        for ch in ("MM2S", "S2MM"):
            self.read_reg(Regs.BASE[ch] + Regs.DMASR, Regs.HALTED, Regs.HALTED | Regs.IDLE)

    def start(self, channel, irq=True):
        """PG021 chapter 4, DR mode steps 1 and 2: run/stop bit, halted bit deasserts, interrupt enables."""
        base = Regs.BASE[channel]
        self.comment(f"start {channel}")
        self.write_reg(base + Regs.DMACR, Regs.IRQ_THRESHOLD_RESET | Regs.RS)
        self.poll_reg(base + Regs.DMASR, 0, Regs.HALTED)
        if irq:
            self.write_reg(base + Regs.DMACR, Regs.IRQ_THRESHOLD_RESET | Regs.RS | Regs.IOC_IRQ_EN | Regs.ERR_IRQ_EN)

    def transfer(self, t):
        """PG021 chapter 4, DR mode: address (and its MSB register above 32 address bits), the length as the last
        write, completion, IOC_Irq cleared by writing one."""
        base = Regs.BASE[t.channel]
        self.comment(f"{t.channel} transfer of {len(t.data)} bytes at 0x{t.addr:X}")
        self.write_reg(base + Regs.ADDR, t.addr & 0xFFFFFFFF)
        if self.addr_width > 32:
            self.write_reg(base + Regs.ADDR_MSB, t.addr >> 32)
        if t.channel == "MM2S":
            self.memory.append((t.addr, t.data))
            self.write_reg(base + Regs.LENGTH, len(t.data))
            self.packet("E", t.data)
        else:
            self.write_reg(base + Regs.LENGTH, t.buffer_len or len(t.data))
            self.packet("S", t.data)
            self.expected.append((t.addr, t.data))
        if t.irq:
            self.wait_irq(t.channel, 1)
        else:
            self.poll_reg(base + Regs.DMASR, Regs.IDLE, Regs.IDLE)
        self.read_reg(base + Regs.DMASR, Regs.IDLE | Regs.IOC_IRQ, Regs.STATE)
        self.write_reg(base + Regs.DMASR, Regs.IOC_IRQ)
        if t.irq:
            self.wait_irq(t.channel, 0)
        if t.channel == "S2MM":
            self.read_reg(base + Regs.LENGTH, len(t.data))
        self.lines.append("A")

    # -----------------------------------------------------------------------------------------------------------------
    # Files
    # -----------------------------------------------------------------------------------------------------------------
    @staticmethod
    def _image(ranges):
        return "".join(f"0x{addr:016X} " + " ".join(f"{b:02X}" for b in data) + "\n" for addr, data in ranges)

    def write(self, directory):
        directory = Path(directory)
        directory.mkdir(parents=True, exist_ok=True)
        (directory / "sequence.txt").write_text("\n".join(self.lines) + "\n", encoding="utf-8", newline="\n")
        (directory / "memory.txt").write_text(self._image(self.memory), encoding="utf-8", newline="\n")
        (directory / "expected_memory.txt").write_text(self._image(self.expected), encoding="utf-8", newline="\n")


def dr_reference():
    """Reference scenario of the model test (hdl/odma_pkg, TC-PKG-11): reset, one MM2S and one S2MM transfer with
    interrupt above 4 GB at unaligned addresses, one MM2S transfer by polling."""
    s = Scenario("dr_reference", addr_width=64)
    s.reset()
    s.start("MM2S")
    s.start("S2MM")
    s.transfer(DrTransfer("MM2S", 0x1_0000_0103, count_bytes(37, 0x10)))
    s.transfer(DrTransfer("S2MM", 0x1_0000_2005, count_bytes(29, 0x80), buffer_len=64))
    s.transfer(DrTransfer("MM2S", 0x3000, count_bytes(8, 0xC0), irq=False))
    return s


SCENARIOS = {"dr_reference": dr_reference}


def main():
    if len(sys.argv) != 3 or sys.argv[1] not in SCENARIOS:
        sys.exit(f"usage: python {sys.argv[0]} <{'|'.join(SCENARIOS)}> <directory>")
    SCENARIOS[sys.argv[1]]().write(sys.argv[2])


if __name__ == "__main__":
    main()
